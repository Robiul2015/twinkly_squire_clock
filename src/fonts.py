FONTS = {"3x5": FONT_3X5, "5x7": FONT_5X7}


def get_glyph(char, font_name="3x5"):
    """Get bitmap data for a character from the specified font."""
    font = FONTS.get(font_name)
    if font is None:
        raise ValueError(f"Unknown font: {font_name}")
    glyph = font.get(char)
    if glyph is None:
        sample = font.get("0", [[0]])
        return [[0] * len(sample[0]) for _ in range(len(sample))]
    return glyph


def measure_text(text, font_name="3x5", spacing=1):
    """Calculate pixel width and height of rendered text."""
    if not text:
        return (0, 0)
    height = len(FONTS[font_name].get("0", [[0]]))
    width = 0
    for i, ch in enumerate(text):
        width += len(get_glyph(ch, font_name)[0])
        if i < len(text) - 1:
            width += spacing
    return (width, height)
